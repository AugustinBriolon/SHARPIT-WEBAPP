/**
 * Translates the structured race formats catalog into the Swift source consumed by
 * the native iOS client. The web/shared app package is the single source of truth (ADR-082);
 * this module holds the pure translation, and `scripts/export-ios-tokens.ts` is the
 * file-system wrapper around it.
 */

import {
  RACE_DISCIPLINES,
  RACE_FORMATS,
  type RaceDiscipline,
  type RaceDistances,
} from './race-formats';

const DISCIPLINE_SWIFT_CASE: Record<RaceDiscipline, string> = {
  RUN: '.run',
  TRAIL: '.trail',
  BIKE: '.bike',
  SWIM: '.swim',
  TRIATHLON: '.triathlon',
  DUATHLON: '.duathlon',
  SWIMRUN: '.swimrun',
};

function formatSwiftDistances(d: RaceDistances): string {
  const parts: string[] = [];
  if (d.swimM) {
    parts.push(`swimM: ${d.swimM.toLocaleString('en-US').replace(/,/g, '_')}`);
  }
  if (d.bikeM) {
    parts.push(`bikeM: ${d.bikeM.toLocaleString('en-US').replace(/,/g, '_')}`);
  }
  if (d.runM) {
    parts.push(`runM: ${d.runM.toLocaleString('en-US').replace(/,/g, '_')}`);
  }
  if (d.run2M) {
    parts.push(`run2M: ${d.run2M.toLocaleString('en-US').replace(/,/g, '_')}`);
  }
  if (d.segments) {
    parts.push(`segments: ${d.segments}`);
  }
  return parts.length > 0 ? `.init(${parts.join(', ')})` : '.init()';
}

export function renderIosRaceFormats(): string {
  const entriesByDiscipline: Record<RaceDiscipline, string[]> = {
    RUN: [],
    TRAIL: [],
    BIKE: [],
    SWIM: [],
    TRIATHLON: [],
    DUATHLON: [],
    SWIMRUN: [],
  };

  for (const f of RACE_FORMATS) {
    const caseName = DISCIPLINE_SWIFT_CASE[f.discipline];
    const distances = formatSwiftDistances(f.distances);
    const editable = f.editableDistances ? ', editable: true' : '';
    entriesByDiscipline[f.discipline].push(
      `        entry(${caseName}, "${f.key}", "${f.label}", "${f.shortLabel}", ${distances}${editable}),`,
    );
  }

  const catalogEntries = RACE_DISCIPLINES.map((discipline) => {
    const lines = entriesByDiscipline[discipline];
    return `        // ${discipline}\n${lines.join('\n')}`;
  }).join('\n');

  return `// Generated by scripts/export-ios-tokens.ts from packages/app/src/lib/goals/race-formats.ts.
// DO NOT EDIT DIRECTLY. Run 'yarn tokens:ios' to regenerate.

import Foundation

/// Structured race catalog (ADR-082) — generated from \`packages/app/src/lib/goals/race-formats.ts\`.
nonisolated enum RaceDiscipline: String, CaseIterable, Identifiable, Codable, Sendable {
    case run = "RUN"
    case trail = "TRAIL"
    case bike = "BIKE"
    case swim = "SWIM"
    case triathlon = "TRIATHLON"
    case duathlon = "DUATHLON"
    case swimrun = "SWIMRUN"

    var id: String { rawValue }

    var label: String {
        switch self {
        case .run: String(localized: "Course à pied")
        case .trail: String(localized: "Trail")
        case .bike: String(localized: "Vélo")
        case .swim: String(localized: "Natation")
        case .triathlon: String(localized: "Triathlon")
        case .duathlon: String(localized: "Duathlon")
        case .swimrun: String(localized: "Swimrun")
        }
    }

    /// Disciplines offered from the athlete's practiced sports.
    static func offered(for sports: Set<String>) -> [RaceDiscipline] {
        var result: [RaceDiscipline] = []
        if sports.contains("run") {
            result.append(.run)
            result.append(.trail)
        }
        if sports.contains("bike") { result.append(.bike) }
        if sports.contains("swim") { result.append(.swim) }
        if sports.contains("triathlon") {
            result.append(contentsOf: [.triathlon, .duathlon, .swimrun])
        } else {
            if sports.contains("run"), sports.contains("bike") { result.append(.duathlon) }
            if sports.contains("run"), sports.contains("swim") { result.append(.swimrun) }
            if sports.contains("run"), sports.contains("bike"), sports.contains("swim") {
                result.append(.triathlon)
            }
        }
        var seen = Set<RaceDiscipline>()
        return result.filter { seen.insert($0).inserted }
    }

    /// Best default when opening the goal step.
    static func preferred(for sports: Set<String>) -> RaceDiscipline? {
        let options = offered(for: sports)
        if sports.contains("triathlon"), options.contains(.triathlon) { return .triathlon }
        if sports.contains("run"), options.contains(.run) { return .run }
        if sports.contains("bike"), options.contains(.bike) { return .bike }
        if sports.contains("swim"), options.contains(.swim) { return .swim }
        return options.first
    }
}

nonisolated struct RaceDistances: Equatable, Codable, Sendable {
    var swimM: Int?
    var bikeM: Int?
    var runM: Int?
    var run2M: Int?
    var segments: Int?
}

nonisolated struct RaceFormatEntry: Identifiable, Equatable, Sendable {
    var id: String { key }
    let discipline: RaceDiscipline
    let key: String
    let label: String
    let shortLabel: String
    let distances: RaceDistances
    let editableDistances: Bool
}

/// Catalog used by onboarding and Objectifs — keys must match the server.
nonisolated enum RaceFormatCatalog {
    static let all: [RaceFormatEntry] = [
${catalogEntries}
    ]

    static func formats(for discipline: RaceDiscipline) -> [RaceFormatEntry] {
        all.filter { $0.discipline == discipline }
    }

    static func entry(key: String) -> RaceFormatEntry? {
        all.first { $0.key == key }
    }

    private static func entry(
        _ discipline: RaceDiscipline,
        _ key: String,
        _ label: String,
        _ shortLabel: String,
        _ distances: RaceDistances,
        editable: Bool = false
    ) -> RaceFormatEntry {
        RaceFormatEntry(
            discipline: discipline,
            key: key,
            label: label,
            shortLabel: shortLabel,
            distances: distances,
            editableDistances: editable
        )
    }
}
`;
}
